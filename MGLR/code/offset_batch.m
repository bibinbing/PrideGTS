function results = offset_batch(opts)
% Processes all configured input files.

inputFiles = offset_inputs(opts.inputPaths);
if isempty(inputFiles)
    error('offset:NoInputFiles', 'No input files were configured or discovered.');
end

results = repmat(struct( ...
    'inputFile', '', ...
    'station', '', ...
    'format', '', ...
    'success', false, ...
    'outputFile', '', ...
    'offsetCount', 0, ...
    'knownConstraintCount', 0, ...
    'transientPairCount', 0, ...
    'correctedOffsetCount', 0, ...
    'removedNonfiniteCount', 0, ...
    'gapCount', 0, ...
    'lsVceConverged', false, ...
    'lsVceIterations', 0, ...
    'whiteVariance', NaN, ...
    'flickerVariance', NaN, ...
    'message', ''), numel(inputFiles), 1);

for i = 1:numel(inputFiles)
    results(i).inputFile = inputFiles{i};
    try
        result = offset_one(inputFiles{i}, opts);
        results(i).station = result.station;
        results(i).format = result.format;
        results(i).success = true;
        results(i).outputFile = result.outputFile;
        results(i).offsetCount = height(result.offsetTable);
        results(i).knownConstraintCount = ...
            result.detection.knownConstraintCount;
        results(i).transientPairCount = result.detection.transientPairCount;
        results(i).correctedOffsetCount = result.detection.correctedOffsetCount;
        results(i).removedNonfiniteCount = structScalar(result.quality, ...
            'removedNonfiniteCount', 0);
        results(i).gapCount = structScalar(result.quality, 'gapCount', 0);
        finalNoise = result.detection.finalNoise;
        results(i).lsVceConverged = logical(structScalar(finalNoise, ...
            'lsVceConverged', false));
        results(i).lsVceIterations = structScalar(finalNoise, 'lsVceIterations', 0);
        results(i).whiteVariance = structScalar(finalNoise, 'whiteVariance', NaN);
        results(i).flickerVariance = structScalar(finalNoise, 'flickerVariance', NaN);
        results(i).message = sprintf( ...
            ['Applied %d known constraint(s); detected %d GLR candidate(s); ', ...
            'flagged %d transient pair(s); ', ...
            'corrected %d offsets; removed %d invalid rows; LS-VCE %s'], ...
            results(i).knownConstraintCount, ...
            result.detection.candidateCount, results(i).transientPairCount, ...
            results(i).correctedOffsetCount, results(i).removedNonfiniteCount, ...
            convergenceText(results(i).lsVceConverged));
        fprintf('Processed %s (%s): %s\n', result.station, result.format, results(i).message);
    catch ME
        results(i).success = false;
        results(i).message = ME.message;
        warning('offset:ProcessFailed', 'Failed to process %s: %s', inputFiles{i}, ME.message);
    end
end

end

function value = structScalar(source, fieldName, fallback)
value = fallback;
if isstruct(source) && isfield(source, fieldName)
    candidate = source.(fieldName);
    if (isnumeric(candidate) || islogical(candidate)) && isscalar(candidate) && ...
            (islogical(candidate) || isfinite(candidate))
        value = candidate;
    elseif isnumeric(candidate) && isscalar(candidate) && isnan(candidate) && isnan(fallback)
        value = candidate;
    end
end
end

function textValue = convergenceText(converged)
if converged
    textValue = 'converged';
else
    textValue = 'not converged';
end
end
